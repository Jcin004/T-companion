// Keep upstream untouched; expose only its reviewed connected-fill methods.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=await readFile(new URL('../frontend/vendor/piskel/connected-fill.inc',import.meta.url),'utf8');
const provenance=JSON.parse(await readFile(new URL('../frontend/vendor/piskel/PROVENANCE.json',import.meta.url),'utf8'));
const catalog=JSON.parse(await readFile(new URL('../config/outfit-workshop-sources.json',import.meta.url),'utf8'));
const entry=catalog.sources.find(s=>s.repository==='https://github.com/piskelapp/piskel').files.find(f=>f.path==='src/js/utils/PixelUtils.js');
if(provenance.upstream_sha256!==entry.sha256||createHash('sha256').update(source).digest('hex')!==provenance.excerpt_sha256||source.includes('getLinePixels'))throw Error('Piskel excerpt checksum mismatch');
await writeFile(new URL('../frontend/piskel-connected-fill.js',import.meta.url),
  '// Generated by scripts/build-pixel-tools.mjs. Piskel / Apache-2.0; see vendor/piskel/LICENSE.\n'+
  'const pskl={PixelUtils:{\n'+source+'}};\n'+
  'export const connectedFill=(frame,x,y,color)=>pskl.PixelUtils.paintSimilarConnectedPixelsFromFrame(frame,x,y,color);\n');
